export function getLineage(id: string | null | undefined): Lineage | undefined {
  return LINEAGES.find((lineage) => lineage.id === id);
}

// 神社に保存した系統。null は「名前から自動で判断」、'none' は「どの系統でもない」
export type LineageSetting = LineageId | 'none' | null;

export function guessLineage(name: string, kind: PlaceKind): Lineage | undefined {
  // 豊川稲荷のように、お寺でも名前に神社の系統の言葉が入ることがある
  if (kind !== 'shrine') return undefined;
  return LINEAGES.find((lineage) => lineage.keywords.test(name));
}

export function lineageOf(shrine: { name: string; kind: PlaceKind; lineage: string | null }): Lineage | undefined {
  if (shrine.lineage === 'none') return undefined;
  return getLineage(shrine.lineage) ?? guessLineage(shrine.name, shrine.kind);
}
